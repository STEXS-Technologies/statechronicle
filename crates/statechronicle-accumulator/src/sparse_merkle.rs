/// Returns the precomputed empty-subtree hash at `level` (i.e. `default[level]`).
pub fn default_hash(level: usize) -> [u8; 32] {
    DEFAULT_SUBTREE_HASHES
        .get(level)
        .copied()
        .unwrap_or(EMPTY_LEAF_HASH)
}

/// A 32-byte SHA-256 state root.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct StateRoot([u8; 32]);

impl StateRoot {
    /// Wraps a raw 32-byte root.
    pub const fn new(bytes: [u8; 32]) -> Self {
        Self(bytes)
    }

    /// Returns the 32 raw root bytes.
    pub const fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }

    /// The root of the empty tree: `default[256]`.
    pub fn empty() -> Self {
        Self(default_hash(TREE_DEPTH))
    }
}

/// A single leaf update: `key → state_digest`.
#[derive(Clone, Copy, Debug)]
pub struct StateUpdate {
    /// The SMT key whose slot receives `state_digest`.
    pub key: StateKey,
    /// The state digest committed at the key's slot (state hash, §9).
    pub state_digest: [u8; 32],
}

impl StateUpdate {
    /// Constructs a leaf update.
    pub const fn new(key: StateKey, state_digest: [u8; 32]) -> Self {
        Self { key, state_digest }
    }
}

/// In-memory sparse Merkle tree accumulator (one per tenant).
///
/// Maintains the leaf set; the root and proofs are computed deterministically
/// from that set on demand. The crate is pure/in-memory — persistence is the
/// ports crate's job.
#[derive(Clone, Debug, Default)]
pub struct StateAccumulator {
    leaves: BTreeMap<StateKey, [u8; 32]>,
}

impl StateAccumulator {
    /// Creates an empty accumulator whose root is `default[256]`.
    pub fn empty() -> Self {
        Self::default()
    }

    /// Returns the current state root.
    pub fn root(&self) -> StateRoot {
        StateRoot(self.compute_root())
    }

    /// Applies a batch of leaf updates and returns the resulting state root.
    ///
    /// Later updates for the same key win. The batch is applied atomically
    /// with respect to the returned root: all updates are reflected in it.
    ///
    /// # Errors
    ///
    /// This operation is total for the v0 baseline; it is declared as
    /// `Result` to match the ADR-005 API surface and to leave room for future
    /// validation failures.
    #[allow(clippy::unnecessary_wraps)]
    pub fn insert_batch(&mut self, updates: &[StateUpdate]) -> Result<StateRoot, AccumulatorError> {
        for update in updates {
            self.leaves.insert(update.key, update.state_digest);
        }
        Ok(StateRoot(self.compute_root()))
    }

    /// Returns an inclusion proof for `key`, or `None` when the key is not
    /// present.
    pub fn prove_inclusion(&self, key: &StateKey) -> Option<InclusionProof> {
        let digest = self.leaves.get(key)?;
        Some(InclusionProof {
            key: *key,
            leaf_hash: leaf_hash(*key, *digest),
            steps: self.collect_steps(key),
        })
    }

    /// Returns a non-membership proof for `key`, or `None` when the key is
    /// present.
    ///
    /// The proof authenticates that the key's slot holds the empty leaf.
    pub fn prove_non_membership(&self, key: &StateKey) -> Option<NonMembershipProof> {
        if self.leaves.contains_key(key) {
            return None;
        }
        Some(NonMembershipProof {
            key: *key,
            leaf_hash: EMPTY_LEAF_HASH,
            steps: self.collect_steps(key),
        })
    }

    /// Verifies an inclusion proof against `root`.
    pub fn verify_inclusion(root: &StateRoot, proof: &InclusionProof) -> bool {
        verify_path(root, &proof.key, proof.leaf_hash, &proof.steps)
    }

    /// Verifies a non-membership proof against `root`.
    pub fn verify_non_membership(root: &StateRoot, proof: &NonMembershipProof) -> bool {
        verify_path(root, &proof.key, proof.leaf_hash, &proof.steps)
    }

    /// Recomputes the tree root from the leaf set.
    fn compute_root(&self) -> [u8; 32] {
        let entries: Vec<(StateKey, [u8; 32])> = self
            .leaves
            .iter()
            .map(|(key, digest)| (*key, *digest))
            .collect();
        node_hash(&entries, 0, entries.len(), TREE_DEPTH)
    }

    /// Collects the non-empty sibling hashes along the path to `key`,
    /// ordered ascending by level (leaf-adjacent first). Levels whose sibling
    /// subtree is empty are skipped; the verifier fills `default[level]`.
    fn collect_steps(&self, key: &StateKey) -> Vec<PathStep> {
        let entries: Vec<(StateKey, [u8; 32])> = self
            .leaves
            .iter()
            .map(|(k, digest)| (*k, *digest))
            .collect();
        let mut steps = Vec::new();
        collect_steps_inner(&entries, 0, entries.len(), TREE_DEPTH, key, &mut steps);
        steps.reverse();
        steps
    }
}

/// Computes the node hash of the subtree at `height` covering
/// `entries[start..end]` (sorted by key).
///
/// A subtree at `height` routes on `key.bit_at(256 - height)`: the root
/// (height 256) routes on bit 0 (the key's most significant bit) and the
/// leaf-adjacent decision (height 1) routes on bit 255.
fn node_hash(
    entries: &[(StateKey, [u8; 32])],
    start: usize,
    end: usize,
    height: usize,
) -> [u8; 32] {
    if start >= end {
        return default_hash(height);
    }
    if height == 0 {
        // A height-0 subtree holds exactly one key (keys are unique).
        let Some((key, digest)) = entries.get(start) else {
            return default_hash(0);
        };
        return leaf_hash(*key, *digest);
    }
    let Some(bit) = TREE_DEPTH.checked_sub(height) else {
        return default_hash(height);
    };
    let split = split_at(entries, start, end, bit);
    let child_height = height.saturating_sub(1);
    let left = node_hash(entries, start, split, child_height);
    let right = node_hash(entries, split, end, child_height);
    internal_hash(left, right)
}

/// Returns the boundary index that partitions `entries[start..end]` by
/// `key.bit_at(bit)`; entries with bit 0 precede entries with bit 1.
fn split_at(entries: &[(StateKey, [u8; 32])], start: usize, end: usize, bit: usize) -> usize {
    let Some(slice) = entries.get(start..end) else {
        return start;
    };
    let relative = slice.partition_point(|(key, _)| !key.bit_at(bit));
    start.saturating_add(relative)
}

/// Walks the tree from the root down to `target`, recording every non-empty
/// sibling (in descending level order; the caller reverses).
fn collect_steps_inner(
    entries: &[(StateKey, [u8; 32])],
    start: usize,
    end: usize,
    height: usize,
    target: &StateKey,
    steps: &mut Vec<PathStep>,
) {
    if height == 0 {
        return;
    }
    let Some(bit) = TREE_DEPTH.checked_sub(height) else {
        return;
    };
    let split = split_at(entries, start, end, bit);
    let (path_start, path_end, sibling_start, sibling_end) = if target.bit_at(bit) {
        (split, end, start, split)
    } else {
        (start, split, split, end)
    };
    let child_height = height.saturating_sub(1);
    if sibling_start < sibling_end {
        let sibling = node_hash(entries, sibling_start, sibling_end, child_height);
        steps.push(PathStep {
            level: child_height,
            sibling,
        });
    }
    collect_steps_inner(entries, path_start, path_end, child_height, target, steps);
}

/// Recombines `leaf_hash` upward through all 256 levels — using the
/// level-tagged sibling when provided, `default[level]` otherwise — and
/// compares the result with `root`.
///
/// Level 0 is the leaf-adjacent decision (routing on key bit 255, default
/// `default[0]`); level 255 is the root decision (key bit 0, default
/// `default[255]`).
fn verify_path(root: &StateRoot, key: &StateKey, leaf_hash: [u8; 32], steps: &[PathStep]) -> bool {
    let by_level: BTreeMap<usize, [u8; 32]> = steps
        .iter()
        .map(|step| (step.level, step.sibling))
        .collect();
    let mut acc = leaf_hash;
    let mut level = 0usize;
    while level < TREE_DEPTH {
        let routing_bit = TREE_DEPTH.wrapping_sub(1).wrapping_sub(level);
        let sibling = by_level
            .get(&level)
            .copied()
            .unwrap_or_else(|| default_hash(level));
        acc = if key.bit_at(routing_bit) {
            internal_hash(sibling, acc)
        } else {
            internal_hash(acc, sibling)
        };
        let Some(next) = level.checked_add(1) else {
            break;
        };
        level = next;
    }
    acc == root.0
}

/// `H(0x10 || left || right)`.
pub fn internal_hash(left: [u8; 32], right: [u8; 32]) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update([INTERNAL_NODE_TAG]);
    hasher.update(left);
    hasher.update(right);
    hasher.finalize().into()
}

/// `H(0x11 || key || state_digest)`.
pub fn leaf_hash(key: StateKey, state_digest: [u8; 32]) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update([LEAF_NODE_TAG]);
    hasher.update(key.as_bytes());
    hasher.update(state_digest);
    hasher.finalize().into()
}

#[cfg(test)]
#[allow(
    clippy::unwrap_used,
    clippy::panic,
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects
)]
mod tests {
    use super::{
        EMPTY_LEAF_HASH, StateAccumulator, StateKey, StateRoot, StateUpdate, default_hash,
        internal_hash, leaf_hash,
    };
    use crate::key::StateKey as Key;

    fn hex(bytes: &[u8; 32]) -> String {
        hex::encode(bytes)
    }

    #[test]
    fn empty_leaf_known_answer() {
        assert_eq!(
            hex(&EMPTY_LEAF_HASH),
            "3abddd594d884ff661d24666372d9fe669a1ec9e616401db6bd2edeb3c397143"
        );
        // EMPTY_LEAF = H(0x11 || [0;32] || [0;32])
        let key = StateKey::new([0u8; 32]);
        assert_eq!(leaf_hash(key, [0u8; 32]), EMPTY_LEAF_HASH);
    }

    #[test]
    fn default_subtree_known_answers() {
        // default[1] = H(0x10 || EMPTY_LEAF || EMPTY_LEAF)
        assert_eq!(
            hex(&default_hash(1)),
            "6461a6d00f23efd18b789a7cb4f6b3a437f0468a2268cf5a46043befaafc2f21"
        );
        assert_eq!(
            internal_hash(EMPTY_LEAF_HASH, EMPTY_LEAF_HASH),
            default_hash(1)
        );
        assert_eq!(
            hex(&default_hash(2)),
            "3152aa7de5f1bab693be587943333797481648fe792eaa3b37a80de532f70473"
        );
        assert_eq!(
            internal_hash(default_hash(1), default_hash(1)),
            default_hash(2)
        );
        assert_eq!(
            hex(&default_hash(256)),
            "c810a0e262c2af1f3b6dbb71c26fe246b0b6b5a3e903759595d17601f0178311"
        );
    }

    #[test]
    fn empty_tree_root_is_default_256() {
        let acc = StateAccumulator::empty();
        assert_eq!(acc.root().as_bytes(), &default_hash(256));
        assert_eq!(StateRoot::empty(), acc.root());
    }

    #[test]
    fn single_leaf_root_matches_default_path() {
        // One leaf with all-zero key: the root is the path that combines the
        // leaf upward with defaults on the right at every level.
        let key = StateKey::new([0u8; 32]);
        let digest = [0x42u8; 32];
        let mut acc = StateAccumulator::empty();
        acc.insert_batch(&[StateUpdate::new(key, digest)]).unwrap();
        let leaf = leaf_hash(key, digest);
        let mut expected = leaf;
        let mut level = 0usize;
        while level < 256 {
            expected = internal_hash(expected, default_hash(level));
            level = level.wrapping_add(1);
        }
        assert_eq!(acc.root().as_bytes(), &expected);
    }

    #[test]
    fn inclusion_proof_roundtrip() {
        let key_a = Key::for_resource("tenant:acme", "asset:sword_001");
        let key_b = Key::for_resource("tenant:acme", "asset:shield_001");
        let key_c = Key::for_resource("tenant:acme", "asset:bow_001");
        let mut acc = StateAccumulator::empty();
        acc.insert_batch(&[
            StateUpdate::new(key_a, [0x01u8; 32]),
            StateUpdate::new(key_b, [0x02u8; 32]),
            StateUpdate::new(key_c, [0x03u8; 32]),
        ])
        .unwrap();
        let root = acc.root();
        for key in [key_a, key_b, key_c] {
            let proof = acc.prove_inclusion(&key).unwrap();
            assert!(StateAccumulator::verify_inclusion(&root, &proof));
        }
    }

    #[test]
    fn non_membership_roundtrip() {
        let key_a = Key::for_resource("tenant:acme", "asset:sword_001");
        let missing = Key::for_resource("tenant:acme", "asset:absent_999");
        let mut acc = StateAccumulator::empty();
        acc.insert_batch(&[StateUpdate::new(key_a, [0x01u8; 32])])
            .unwrap();
        let root = acc.root();
        assert!(acc.prove_inclusion(&missing).is_none());
        let proof = acc.prove_non_membership(&missing).unwrap();
        assert!(StateAccumulator::verify_non_membership(&root, &proof));
    }

    #[test]
    fn non_membership_rejected_for_present_key() {
        let key = Key::for_resource("tenant:acme", "asset:sword_001");
        let mut acc = StateAccumulator::empty();
        acc.insert_batch(&[StateUpdate::new(key, [0x01u8; 32])])
            .unwrap();
        assert!(acc.prove_non_membership(&key).is_none());
    }

    #[test]
    fn tampered_digest_fails_verification() {
        let key_a = Key::for_resource("tenant:acme", "asset:sword_001");
        let key_b = Key::for_resource("tenant:acme", "asset:shield_001");
        let mut acc = StateAccumulator::empty();
        acc.insert_batch(&[
            StateUpdate::new(key_a, [0x01u8; 32]),
            StateUpdate::new(key_b, [0x02u8; 32]),
        ])
        .unwrap();
        let root = acc.root();
        let proof = acc.prove_inclusion(&key_a).unwrap();
        let mut tampered = proof;
        tampered.leaf_hash = leaf_hash(key_a, [0xffu8; 32]);
        assert!(!StateAccumulator::verify_inclusion(&root, &tampered));
    }

    #[test]
    fn root_is_independent_of_insertion_order() {
        let updates = [
            StateUpdate::new(
                Key::for_resource("tenant:acme", "asset:sword_001"),
                [0x01u8; 32],
            ),
            StateUpdate::new(
                Key::for_subject_held("tenant:acme", "asset:sword_001", "account:stexs:player_123"),
                [0x02u8; 32],
            ),
            StateUpdate::new(
                Key::for_resource("tenant:acme", "asset:shield_001"),
                [0x03u8; 32],
            ),
        ];
        let mut forward = StateAccumulator::empty();
        forward.insert_batch(&updates).unwrap();
        let mut reverse = StateAccumulator::empty();
        let mut rev = updates.to_vec();
        rev.reverse();
        reverse.insert_batch(&rev).unwrap();
        assert_eq!(forward.root(), reverse.root());
    }

    #[test]
    fn overwrite_same_key_changes_root() {
        let key = Key::for_resource("tenant:acme", "asset:sword_001");
        let mut acc = StateAccumulator::empty();
        acc.insert_batch(&[StateUpdate::new(key, [0x01u8; 32])])
            .unwrap();
        let first = acc.root();
        acc.insert_batch(&[StateUpdate::new(key, [0x02u8; 32])])
            .unwrap();
        assert_ne!(first, acc.root());
    }
}
