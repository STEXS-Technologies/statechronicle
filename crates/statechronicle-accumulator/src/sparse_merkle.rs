//! Sparse Merkle tree state accumulator (ADR-005).
//!
//! A fixed-256-bit-depth SMT, one per tenant, keyed by SHA-256 domain-
//! separated composite keys ([`crate::key::StateKey`]) with SHA-256 node
//! hashing. Node encoding is the protocol commitment and is locked by the
//! precomputed empty-subtree constants below and by known-answer tests:
//!
//! ```text
//! internal(h)   = H(0x10 || left(h-1) || right(h-1))
//! leaf(key)     = H(0x11 || key || state_digest)
//! EMPTY_LEAF    = H(0x11 || [0;32] || [0;32])        = default[0]
//! default[h]    = H(0x10 || default[h-1] || default[h-1])
//! ```
//!
//! The root of the empty tree is `default[256]`. Because keys are SHA-256
//! images, insertion order never matters: the root is a pure function of the
//! `(key → state_digest)` set. Non-membership proofs are inclusion proofs of
//! the empty leaf (fail-closed per §18.2).

